import assert from 'node:assert';
import { newProgress, finishDailySet, finishMilestone } from './points.ts';
import { DeviceStore, chooseStore, type ProgressStore } from './storage.ts';
let p = newProgress();
p = finishDailySet(p, 100, 4); assert.equal(p.points, 45); assert.equal(p.streak, 1);
p = finishDailySet(p, 100, 5); assert.equal(p.points, 45, 'same day no double reward');
p = finishDailySet(p, 101, 5); assert.equal(p.streak, 2);
const before = p.points;
p = finishDailySet(p, 103, 0); assert.equal(p.streak, 3, 'one missed day forgiven'); assert.ok(p.points >= before, 'points never drop');
p = finishDailySet(p, 105, 1); assert.equal(p.streak, 4, 'new week, one skip forgiven again');
p = finishDailySet(p, 107, 1); assert.equal(p.streak, 1, 'second skip in the same week restarts streak');
p = finishDailySet(p, 120, 1); assert.equal(p.streak, 1); assert.ok(p.points > before);
let r = finishMilestone(p, '5-6', 7); assert.equal(r.passed, false); assert.deepEqual(r.progress.milestones, {}); assert.equal(r.progress.points, p.points);
r = finishMilestone(p, '5-6', 8); assert.equal(r.passed, true); assert.equal(r.progress.milestones['5-6'], true);
const m = new Map<string, string>(); const kv = { getItem: (k: string) => m.get(k) ?? null, setItem: (k: string, v: string) => void m.set(k, v) };
const dev = new DeviceStore(kv); await dev.save('c1', p); assert.deepEqual(await dev.load('c1'), p); assert.equal(await dev.load('c2'), null);
const fake: ProgressStore = { kind: 'drive-appdata', load: async () => null, save: async () => {} };
assert.equal(chooseStore(dev, fake, true, false), dev, 'cloud off for children even with consent');
console.log('ALL PASS');
